#!/usr/bin/env python3
"""Compile the sirius Adreno 616 probe and its GMU firmware against the recorded BSD ABI and archive them.

Same shape as build-sirius-touch.py: the file is built as an external archive rather than a
bsd/conf/files entry, because the XNU makefile generated from conf/files does not pick up a file
added by a patch. The objects join libShengPlatformPower.a, the archive build-xnu force-loads when
CONFIG_XNU_SHENG_PMGR=1.

Phase 2 (sirius-gpu=2) loads a630_gmu.bin, the legacy A630-family GMU firmware linux-sirius uses
for this GPU. It is not committed: it is fetched from 57UU/sirius-distro at a pinned commit, checked
against its SHA-256 and compiled in as sirius_gmu_fw[] (sirius_gmu_fw_words words).
"""
import hashlib
import json
from pathlib import Path
import subprocess

GMU_FW_URL = ('https://raw.githubusercontent.com/57UU/sirius-distro/'
              '010ce33d65e9bcbefa2af35714fe49810189eaa8/firmware/gpu/a630_gmu.bin')
GMU_FW_SHA256 = 'da8d9b1b1f5c1a0b311f32567093b4828f3c80031dd8435f91ac13c664e173a6'
GMU_FW_BYTES = 32768

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'build/sirius-gpu'
OUT.mkdir(parents=True, exist_ok=True)
record = json.loads((ROOT / 'build/xnu/ios-obj/DEVELOPMENT_ARM64_BCM2837/bsd/DEVELOPMENT/bsd_init.o.json')
                    .read_text().strip().rstrip(','))


def compile_c(source, obj):
    command, index = [], 0
    arguments = record['arguments']
    while index < len(arguments):
        value = arguments[index]
        if value == record['file']:
            command.append(str(source))
        elif value == '-o':
            command.extend(['-o', str(obj)])
            index += 1
        elif value == '-Xclang' and arguments[index + 1].startswith('-W'):
            index += 1
        elif not value.startswith('-W'):
            command.append(value)
        index += 1
    command.extend(['-w', '-Wno-error'])
    result = subprocess.run(command, cwd=record['directory'], stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                            text=True)
    (OUT / f'{obj.stem}-compile-command.json').write_text(json.dumps(command, indent=2) + '\n')
    (OUT / f'{obj.stem}-compile.log').write_text(result.stdout)
    if result.returncode:
        raise SystemExit(result.stdout[-6000:])


def gmu_firmware():
    path = OUT / 'a630_gmu.bin'
    if not path.exists() or hashlib.sha256(path.read_bytes()).hexdigest() != GMU_FW_SHA256:
        subprocess.run(['curl', '-fsSL', '--retry', '5', '--retry-delay', '5', '-o', str(path), GMU_FW_URL], check=True)
    data = path.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != GMU_FW_SHA256 or len(data) != GMU_FW_BYTES:
        raise SystemExit(f'a630_gmu.bin: {len(data)} bytes, sha256 {digest}; expected {GMU_FW_BYTES}, {GMU_FW_SHA256}')
    words = [int.from_bytes(data[i:i + 4], 'little') for i in range(0, len(data), 4)]
    lines = [', '.join(f'0x{word:08x}' for word in words[i:i + 8]) for i in range(0, len(words), 8)]
    source = OUT / 'sirius_gmu_fw.c'
    source.write_text(f'/* a630_gmu.bin, {GMU_FW_URL}, sha256 {GMU_FW_SHA256}. Generated by scripts/build-sirius-gpu.py. */\n'
                      f'const unsigned int sirius_gmu_fw_words = {len(words)};\n'
                      f'const unsigned int sirius_gmu_fw[{len(words)}] = {{\n\t' + ',\n\t'.join(lines) + '\n};\n')
    return source


objects = []
for source in (ROOT / 'kits/sirius/sirius_gpu.c', gmu_firmware()):
    obj = OUT / f'{source.stem}.o'
    compile_c(source, obj)
    objects.append(obj)

archive = ROOT / 'build/sheng-platform-power/libShengPlatformPower.a'
archive.parent.mkdir(parents=True, exist_ok=True)
subprocess.run(['xcrun', 'ar', 'rcs', archive, *objects], check=True)
print(f'SiriusGpu: added {", ".join(obj.name for obj in objects)} to {archive}')
